def main() -> None:
    ok = miss = 0
    for rel, pairs in EDITS.items():
        path = ROOT / rel
        if not path.exists():
            print(f"{rel}: 文件不存在，跳过")
            continue
        text = path.read_text(encoding="utf-8")
        missed = []
        for old, new in pairs:
            if old in text:
                text = text.replace(old, new)
                ok += 1
            else:
                missed.append(old.splitlines()[0][:44])
                miss += 1
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"{rel}: 应用 {len(pairs) - len(missed)}/{len(pairs)}")
        for m in missed:
            print("   未命中:", m)
    print(f"\n合计 应用 {ok} / 未命中 {miss}")


if __name__ == "__main__":
    main()
