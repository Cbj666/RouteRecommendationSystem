def main() -> None:
    total_ok = total_miss = 0
    for rel, pairs in EDITS.items():
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        missed = []
        for old, new in pairs:
            if old in text:
                text = text.replace(old, new)
                total_ok += 1
            else:
                missed.append(old.splitlines()[0][:48])
                total_miss += 1
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"{rel}: 应用 {len(pairs) - len(missed)}/{len(pairs)}")
        for m in missed:
            print("   未命中:", m)
    print(f"\n合计 应用 {total_ok} / 未命中 {total_miss}")


if __name__ == "__main__":
    main()
